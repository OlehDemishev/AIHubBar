import AppKit
import Foundation
import Observation

/// One entry of «История буфера» (SPEC-profiles §3, second wave): text or copied files.
struct ClipItem: Codable, Equatable, Identifiable, Sendable {
    enum Kind: String, Codable, Sendable { case text, files }

    var id: String = UUID().uuidString.lowercased()
    var kind: Kind
    /// The text, or the file paths one per line.
    var text: String
    var date: Date
    var pinned = false
    var sourceApp: String?
}

/// What gets recorded and how the list is kept. Pure, so the password rules are tested.
enum ClipboardPolicy {
    /// Markers apps put on the pasteboard for secrets and throwaway copies (nspasteboard.org): never recorded.
    static let concealedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    /// Password managers and keychains: nothing copied while they are in front is recorded.
    static let defaultExcludedApps = [
        "com.1password.1password", "com.agilebits.onepassword7", "com.bitwarden.desktop", "org.keepassxc.keepassxc",
        "com.apple.Passwords", "com.apple.keychainaccess", "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal",
    ]

    static func shouldRecord(types: [String], frontmostApp: String?, excludedApps: [String]) -> Bool {
        if types.contains(where: concealedTypes.contains) { return false }
        if let app = frontmostApp, excludedApps.contains(app) { return false }
        return true
    }

    /// A new copy goes on top; the same text again moves up instead of repeating; pinned entries stay, the rest
    /// beyond the limit fall off.
    static func adding(_ item: ClipItem, to items: [ClipItem], limit: Int) -> [ClipItem] {
        let trimmed = item.text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return items }
        var rest = items
        var new = item
        if let index = rest.firstIndex(where: { $0.kind == item.kind && $0.text == item.text }) {
            new.pinned = rest[index].pinned
            new.id = rest[index].id
            rest.remove(at: index)
        }
        var result = [new] + rest
        var unpinned = 0
        result = result.filter { entry in
            if entry.pinned { return true }
            unpinned += 1
            return unpinned <= limit
        }
        return result
    }
}

/// Watches the pasteboard while «История буфера» is installed and keeps the recent copies. In memory by default;
/// on disk (`clipboard.json`, readable by the user only) only when «Помнить после перезапуска» is on.
@MainActor
@Observable
final class ClipboardHistory {
    private(set) var items: [ClipItem] = []
    var isActive: () -> Bool = { false }

    private let settings: AppSettings
    private let file = SessionFiles.supportDirectory.appending(path: "clipboard.json")
    private var lastChange = NSPasteboard.general.changeCount
    private var loop: Task<Void, Never>?
    private var loaded = false

    init(settings: AppSettings) {
        self.settings = settings
    }

    func start() {
        guard loop == nil else { return }
        loop = Task { [weak self] in
            while !Task.isCancelled {
                guard let self else { return }
                poll()
                try? await Task.sleep(for: .milliseconds(700))
            }
        }
    }

    private func poll() {
        guard isActive() else {
            if !items.isEmpty || loaded { items = []; loaded = false }
            return
        }
        if !loaded {
            loaded = true
            if settings.clipboardRemember { items = load() }
        }
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        let types = pasteboard.types?.map(\.rawValue) ?? []
        let front = NSWorkspace.shared.frontmostApplication
        guard ClipboardPolicy.shouldRecord(types: types, frontmostApp: front?.bundleIdentifier, excludedApps: settings.clipboardExcludedApps) else { return }
        let item: ClipItem
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            item = ClipItem(kind: .files, text: urls.map(\.path).joined(separator: "\n"), date: .now, sourceApp: front?.localizedName)
        } else if let text = pasteboard.string(forType: .string) {
            item = ClipItem(kind: .text, text: text, date: .now, sourceApp: front?.localizedName)
        } else {
            return
        }
        items = ClipboardPolicy.adding(item, to: items, limit: settings.clipboardLimit)
        save()
    }

    /// Puts an entry back on the pasteboard; it moves to the top.
    func copy(_ item: ClipItem) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        switch item.kind {
        case .text: pasteboard.setString(item.text, forType: .string)
        case .files: pasteboard.writeObjects(item.text.split(separator: "\n").map { URL(fileURLWithPath: String($0)) as NSURL })
        }
        lastChange = pasteboard.changeCount
        var moved = item
        moved.date = .now
        items = ClipboardPolicy.adding(moved, to: items, limit: settings.clipboardLimit)
        save()
    }

    func togglePin(_ item: ClipItem) {
        guard let index = items.firstIndex(where: { $0.id == item.id }) else { return }
        items[index].pinned.toggle()
        save()
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    /// Everything but the pinned entries.
    func clear() {
        items.removeAll { !$0.pinned }
        save()
    }

    /// Called when «Помнить после перезапуска» changes: switched off, the file goes.
    func rememberChanged() {
        if settings.clipboardRemember { save() } else { try? FileManager.default.removeItem(at: file) }
    }

    private func save() {
        guard settings.clipboardRemember else { return }
        let encoder = JSONEncoder()
        encoder.dateEncodingStrategy = .iso8601
        guard let data = try? encoder.encode(items) else { return }
        try? FileManager.default.createDirectory(at: file.deletingLastPathComponent(), withIntermediateDirectories: true)
        FileManager.default.createFile(atPath: file.path, contents: data, attributes: [.posixPermissions: 0o600])
    }

    private func load() -> [ClipItem] {
        let decoder = JSONDecoder()
        decoder.dateDecodingStrategy = .iso8601
        return (try? Data(contentsOf: file)).flatMap { try? decoder.decode([ClipItem].self, from: $0) } ?? []
    }
}
